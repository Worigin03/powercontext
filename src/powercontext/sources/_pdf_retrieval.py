@dataclass(frozen=True)
class _Page:
    citation: MemoryCitation
    source_id: str
    document: str
    report: str
    number: int | None
    body: str


@dataclass(frozen=True)
class _PageTerms:
    words: tuple[str, ...]
    counts: Counter[str]
    text: str
    heading: str
    value_rows: str
    statement: str | None


@dataclass(frozen=True)
class _PageIndex:
    memory_ref: object
    source_type: str
    pages: tuple[_Page, ...]
    terms: tuple[_PageTerms, ...]


_PAGE_INDEXES = WeakKeyDictionary()


@dataclass(frozen=True)
class _Match:
    page: _Page
    score: float
    clauses: tuple[float, ...]
    statement: str | None


def _tokens(text: str) -> tuple[str, ...]:
    text = unicodedata.normalize("NFKC", text).casefold()
    text = re.sub(r"['’]s\b", "s", text)  # noqa: RUF001
    words = []
    for word in _WORD.findall(text):
        if word.endswith(("taxes", "losses", "businesses")):
            word = word[:-2]
        elif len(word) > 4 and word.endswith("ies"):
            word = word[:-3] + "y"
        elif len(word) > 3 and word.endswith("s") and not word.endswith(("ss", "us", "is")):
            word = word[:-1]
        words.append(word)
    return tuple(words)


def _subject(document: str) -> tuple[str, ...]:
    issuer = re.split(r"(?:19|20)\d{2}|\b10[-_\s]?[kq]\b", document.casefold(), maxsplit=1)[0]
    return tuple(
        word
        for word in _WORD.findall(issuer)
        if word
        not in {"annual", "report", "corporation", "corp", "inc", "company", "co", "ltd", "plc", "the", "and", "fy"}
    )


def _mentions(issuer: tuple[str, ...], question: str) -> bool:
    name = "".join(issuer)
    return len(name) >= 2 and bool(
        re.search(r"\b" + r"[\s._'’&-]*".join(map(re.escape, name)) + r"(?:['’]s)?\b", question)  # noqa: RUF001
    )


def _heading_lines(body: str) -> list[str]:
    body = re.sub(r"\A\s*t\s*able\s+of\s+contents\b[^\S\n]*", "", body, flags=re.IGNORECASE)
    return [line.strip() for line in body.splitlines() if line.strip()]


_TITLE = re.compile(
    r"(?:(?:consolidated|combined|condensed|unaudited)\s+)*"
    r"(?:(?:statements?\s+of\s+(?:(?:consolidated|combined)\s+)?)"
    r"(?P<kind>cash flows?|comprehensive (?:income|loss)|income|operations|earnings|profit and loss|"
    r"financial position|financial condition|changes in (?:(?:stockholders|shareholders)[\u2019']? )?equity|equity)"
    r"(?:\s+and\s+(?:comprehensive (?:income|loss)|retained earnings))?|balance sheets?)"
    r"(?:\s*\([^)]*\))*",
)


def _statement(lines: list[str], numeric_tokens: int) -> str | None:
    if numeric_tokens < 6:
        return None
    for start in range(min(8, len(lines))):
        for end in range(start + 1, min(len(lines), start + 3) + 1):
            title = " ".join(" ".join(lines[start:end]).casefold().split())
            match = _TITLE.fullmatch(title)
            if match is None:
                continue
            kind = match["kind"] or "financial position"
            if kind.startswith("financial"):
                return _BALANCE
            if kind.startswith("cash"):
                return _CASH
            if kind.startswith("comprehensive"):
                return _COMPREHENSIVE
            if kind.endswith("equity"):
                return _EQUITY
            return _INCOME
    return None


def _index_page(body: str) -> _PageTerms:
    lines = _heading_lines(body)
    words = _tokens(body)
    # A numeric line or a standalone cell directly after a label can carry a
    # line-item value. Keep rows separate so unrelated words cannot form labels.
    rows = [
        line
        for index, line in enumerate(lines)
        if re.search(r"\d", line) or (index + 1 < len(lines) and re.match(r"[$( -]*\d", lines[index + 1]))
    ]
    return _PageTerms(
        words,
        Counter(words),
        f" {' '.join(words)} ",
        f" {' '.join(_tokens(' '.join(lines[:5])))} ",
        "\n".join(f" {' '.join(_tokens(row))} " for row in rows),
        _statement(lines, sum(word.isdigit() for word in words)),
    )


def _keyword_score(page: _PageTerms, weights: dict[str, float], pairs: tuple[str, ...], mean_length: float) -> float:
    length_norm = 1.2 * (0.55 + 0.45 * len(page.words) / mean_length)
    matched = {word: page.counts[word] for word in weights if page.counts[word]}
    document = sum(weights[word] * count * 2.2 / (count + length_norm) for word, count in matched.items())
    if not matched:
        return 0.0
    # Find the best local concentration of query words without copying windows.
    # The windows contain overlapping spans of 64 words.
    windows = [0.0] * (1 + len(page.words) // 32)
    for position, word in enumerate(page.words):
        weight = weights.get(word, 0.0)
        if weight:
            window = position // 32
            windows[window] += weight
            if window:
                windows[window - 1] += weight
    phrase = sum(
        min(3.0, 0.5 * sum(weights.get(word, 0.0) for word in pair.split())) for pair in pairs if pair in page.text
    )
    return document + 0.45 * min(max(windows), 2 * sum(weights[word] for word in matched)) + phrase


def _clause_score(page: _PageTerms, labels: tuple[str, ...], role: str | None) -> float:
    best = 0.0
    for label in labels:
        if label in page.text:
            specificity = min(4, len(label.split()))
            score = 2 + 0.6 * specificity
            if label in page.value_rows:
                score += 2.0
            if label in page.heading:
                score += 3.0
            best = max(best, score)
    if role is not None and page.statement == role:
        # A true statement remains eligible when the report uses an unfamiliar
        # line-item label. Exact labels and numeric evidence strengthen it.
        best += 5.0
    return best


def _neighbor_follows(anchor: _Match, candidate: _Page) -> bool:
    lines = _heading_lines(candidate.body)
    if not lines:
        return False
    heading = lines[0].casefold()
    if re.match(r"^[2-9]\d*[.)]\s", heading) or "(continued)" in heading:
        return True
    return anchor.statement == _CASH and any(
        re.fullmatch(
            r"(?:(?:cash flows? from|net cash (?:used in|provided by))\s+)?"
            r"(?:investing|financing|operating) activities[:.]?",
            line.casefold(),
        )
        for line in lines[:3]
    )


def _rank_pages(
    pages: tuple[_Page, ...],
    indexed: tuple[_PageTerms, ...],
    question: str,
    native: dict[tuple[str, str], int],
    limit: int,
) -> tuple[_Page, ...]:
    subjects = {page.document: _subject(page.document) for page in pages}
    named = {document for document, issuer in subjects.items() if _mentions(issuer, question)}
    if named:
        indexed = tuple(terms for page, terms in zip(pages, indexed, strict=True) if page.document in named)
        pages = tuple(page for page in pages if page.document in named)
    issuer_words = {word for document in named for word in _tokens(" ".join(subjects[document]))}
    question = re.sub(r"\b(?:fy|fiscal\s+year)\s*['’]?(\d{4})\b", r"\1", question)  # noqa: RUF001
    years = set(_YEAR.findall(question))
    query_words = tuple(
        word for word in _tokens(question) if word not in _STOP and word not in issuer_words and not word.isdigit()
    )
    pairs = tuple(dict.fromkeys(f" {first} {second} " for first, second in pairwise(query_words)))
    clauses = tuple(
        dict.fromkeys(
            clause for pattern, components in _CONCEPTS if re.search(pattern, question) for clause in components
        )
    )
    labels = tuple(tuple(f" {' '.join(_tokens(label))} " for label in clause.labels) for clause in clauses)
    frequency = Counter(term for page in indexed for term in page.counts)
    mean_length = max(1.0, sum(len(page.words) for page in indexed) / len(indexed))
    weights = {
        word: max(0.2, math.log1p((len(pages) - frequency[word] + 0.5) / (frequency[word] + 0.5)))
        for word in query_words
    }
    matches = []
    for page, terms in zip(pages, indexed, strict=True):
        lexical = _keyword_score(terms, weights, pairs, mean_length)
        evidence = tuple(
            _clause_score(terms, variants, clause.statement) for clause, variants in zip(clauses, labels, strict=True)
        )
        score = lexical + max(evidence, default=0.0) + 0.2 * sum(evidence)
        if not score:
            continue
        if years.intersection(_YEAR.findall(page.document)):
            score *= 1.12
        if years.intersection(terms.counts):
            score *= 1.05
        rank = native.get((page.citation.entry_id, page.citation.entry_version_id))
        if rank is not None:
            score += 0.75 / math.sqrt(rank)
        matches.append(_Match(page, score, evidence, terms.statement))
    matches.sort(key=lambda match: (-match.score, match.page.source_id))
    return _select_pages(matches, pages, len(clauses), limit)


def _primary_matches(ranked: list[_Match], clause_count: int) -> list[_Match]:
    reports: dict[str, list[_Match]] = {}
    for match in ranked:
        reports.setdefault(match.page.report, []).append(match)

    # Cover every required component before adding alternative pages for a
    # component whose evidence spans several sections or physical pages.
    primaries = []
    alternatives = []
    for index in range(clause_count):
        for report in reports.values():
            candidates = sorted(
                (match for match in report if match.clauses[index]),
                key=lambda match: (match.clauses[index], match.score),
                reverse=True,
            )
            if candidates:
                primaries.append(candidates[0])
                alternatives.extend(candidates[1:8])
    if len(reports) > 1:
        primaries.extend(report[0] for report in reports.values())
    primaries.extend(alternatives)
    return primaries


def _select_pages(ranked: list[_Match], pages: tuple[_Page, ...], clause_count: int, limit: int) -> tuple[_Page, ...]:
    by_position = {(page.report, page.number): page for page in pages if page.number is not None}
    selected: dict[str, _Page] = {}
    added_neighbors = 0
    for match in (*_primary_matches(ranked, clause_count), *ranked):
        page = match.page
        if page.source_id in selected:
            continue
        selected[page.source_id] = page
        if len(selected) >= limit:
            break
        if page.number is not None and added_neighbors < max(1, limit // 5):
            neighbor = by_position.get((page.report, page.number + 1))
            if neighbor and neighbor.source_id not in selected and _neighbor_follows(match, neighbor):
                selected[neighbor.source_id] = neighbor
                added_neighbors += 1
                if len(selected) >= limit:
                    break
    return tuple(selected.values())


async def _load_page_index(memory: ScopedMemoryApplication, source_type: str) -> _PageIndex:
    snapshot = await memory.list()
    cached = _PAGE_INDEXES.get(memory)
    if cached is not None and cached.memory_ref == snapshot.memory_ref and cached.source_type == source_type:
        return cached

    pages = []
    for record in snapshot.entries:
        identities = {ref.source_id for ref in record.entry.sources if ref.source_type == source_type}
        if len(identities) != 1:
            continue
        source_id = identities.pop()
        physical = _PAGE_ID.fullmatch(source_id)
        if physical is not None:
            document = unquote(physical[1])
            # Memory stores canonical NFC text with outer whitespace removed.
            prefix = unicodedata.normalize("NFC", document).lstrip() + "\n"
            separator = "\n" if record.entry.text.startswith(prefix) else ""
            body = record.entry.text[len(prefix) :]
            report = f"{physical[1]}:{physical[2]}"
            number = int(physical[3])
        else:
            document, separator, body = record.entry.text.partition("\n")
            report = document
            number = None
        if separator and body.strip():
            pages.append(_Page(record.citation, source_id, document, report, number, body))

    index = _PageIndex(
        snapshot.memory_ref,
        source_type,
        tuple(pages),
        tuple(_index_page(page.body) for page in pages),
    )
    if snapshot.memory_ref is not None:
        _PAGE_INDEXES[memory] = index
    return index


async def recall_pages(
    memory: ScopedMemoryApplication, question: str, *, limit: int, source_type: str
) -> tuple[MemoryCitation, ...]:
    """Use the scoped Memory's own entries and citations for offline retrieval."""
    from powercontext.builtin.runtime import SearchMemoryRequest

    if not isinstance(limit, int) or isinstance(limit, bool) or limit < 1 or not question.strip():
        return ()

    normalized = unicodedata.normalize("NFKC", question).casefold()
    query = " ".join(dict.fromkeys(word for word in _tokens(normalized) if word not in _STOP))
    results = None
    if query:
        results = await memory.search(SearchMemoryRequest(query=query, mode="fts", limit=64))
        cached = _PAGE_INDEXES.get(memory)
        if cached is not None and cached.memory_ref == results.memory_ref and cached.source_type == source_type:
            index = cached
        else:
            index = await _load_page_index(memory, source_type)
    else:
        index = await _load_page_index(memory, source_type)
    if not index.pages:
        return ()

    native = {}
    if results is not None and results.memory_ref == index.memory_ref:
        native = {(hit.entry_id, hit.entry_version_id): rank for rank, hit in enumerate(results.hits, 1)}
    return tuple(page.citation for page in _rank_pages(index.pages, index.terms, normalized, native, limit))
